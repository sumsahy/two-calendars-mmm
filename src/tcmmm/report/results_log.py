"""Write docs/results_log.md from results JSON, so every number in the docs traces to a run.

    python -m tcmmm.report.results_log
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
VERS = ["oracle", "naive_445", "naive_weekstart", "corrected"]
PRIORS = [("spend_share", "results_spend_share", "Main analysis: spend-share prior"),
          ("equal", "results", "Sensitivity: equal prior")]


def _load(d: Path) -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(d.glob("*/result.json"))]


def _cell(r: dict, v: str) -> str:
    res = r["versions"][v]
    p, verdict = res["p_shift_helps"], res["verdict"]
    wrong = (verdict == "Holds" and r["truth"]["verdict_if_known"] == "Hurts") or \
            (verdict == "Reverses" and r["truth"]["verdict_if_known"] == "Helps")
    short = {"Holds": "Holds", "Reverses": "Reverses", "Leans holds, not supported": "n.s. (leans holds)",
             "Leans reverses, not supported": "n.s. (leans rev.)"}[verdict]
    return f"{p:.2f} {short}" + (" **WRONG**" if wrong else "")


def scenario_table(runs: list[dict]) -> list[str]:
    out = ["| Run | Truth: Δ sales | " + " | ".join(VERS) + " |", "|---|---|" + "---|" * len(VERS)]
    for r in runs:
        t = r["truth"]
        out.append(f"| {r['scenario']} | {t['verdict_if_known']} ({100*t['shift_delta_pct_of_sales']:+.2f}%) | "
                   + " | ".join(_cell(r, v) for v in VERS) + " |")
    return out


def recovery_table(r: dict) -> list[str]:
    t = r["truth"]
    out = ["| Version | TV share (truth {:.1%}) | Email share (truth {:.1%}) | TV mROI (truth {:.2f}) | Digital mROI (truth {:.2f}) | Email mROI (truth {:.2f}) | Divergences | max r-hat |".format(
        t["contribution_share"]["tv"], t["contribution_share"]["email"], t["marginal_roi"]["tv"],
        t["marginal_roi"]["digital"], t["marginal_roi"]["email"]), "|---|---|---|---|---|---|---|---|"]
    for v in VERS:
        x = r["versions"][v]
        cs, mr, dg = x["contribution_share"], x["marginal_roi"], x["diagnostics"]
        f = lambda d, k, pct: (f"{d[k]['mean']:.1%} [{d[k]['ci90'][0]:.1%}, {d[k]['ci90'][1]:.1%}]" if pct
                               else f"{d[k]['mean']:.2f} [{d[k]['ci90'][0]:.2f}, {d[k]['ci90'][1]:.2f}]")
        out.append(f"| {v} | {f(cs,'tv',1)} | {f(cs,'email',1)} | {f(mr,'tv',0)} | {f(mr,'digital',0)} | "
                   f"{f(mr,'email',0)} | {dg['divergences']} | {dg['max_rhat']:.3f} |")
    return out


def tally(runs: list[dict]) -> dict:
    c = {v: {"wrong_confident": 0, "correct_confident": 0, "not_supported": 0} for v in VERS}
    for r in runs:
        for v in VERS:
            verdict = r["versions"][v]["verdict"]
            truth = r["truth"]["verdict_if_known"]
            if verdict in ("Holds", "Reverses"):
                ok = (verdict == "Holds") == (truth == "Helps")
                c[v]["correct_confident" if ok else "wrong_confident"] += 1
            else:
                c[v]["not_supported"] += 1
    return c


def bias_vs_oracle(runs: list[dict]) -> dict:
    out = {}
    for v in VERS:
        d = [r["versions"][v]["p_shift_helps"] - r["versions"]["oracle"]["p_shift_helps"] for r in runs]
        out[v] = {"mean": sum(d) / len(d), "higher": sum(x > 0 for x in d), "n": len(d)}
    return out


def build() -> str:
    L = ["# Results log", "",
         "Generated by `python -m tcmmm.report.results_log` from `results*/**/result.json`. Do not edit by hand.",
         "Cells show P(15% shift helps) and the pre-registered verdict (n.s. = not supported at 0.80). "
         "**WRONG** = a confident verdict that contradicts the known truth.", ""]
    first = None
    for key, d, title in PRIORS:
        runs = _load(ROOT / d)
        reps = _load(ROOT / d / "replicates")
        if not runs:
            continue
        L += [f"## {title}", "", "### Scenario sweep (one seed each)", ""] + scenario_table(runs) + [""]
        if reps:
            L += ["### Replicates (new random worlds, same true parameters)", ""] + scenario_table(reps) + [""]
        allr = runs + reps
        tl = tally(allr)
        L += [f"### Tally across all {len(allr)} runs", "", "| Version | Confident and right | Not supported | Confident and WRONG |",
              "|---|---|---|---|"]
        L += [f"| {v} | {tl[v]['correct_confident']} | {tl[v]['not_supported']} | {tl[v]['wrong_confident']} |" for v in VERS]
        b = bias_vs_oracle(allr)
        L += ["", "### How far each version moves P(shift helps) away from the perfect-data oracle", "",
              "| Version | Mean change in P vs oracle | Runs where P is higher than oracle |", "|---|---|---|"]
        L += [f"| {v} | {b[v]['mean']:+.3f} | {b[v]['higher']} of {b[v]['n']} |" for v in VERS if v != "oracle"]
        main = next((r for r in runs if r["scenario"] == "main"), None)
        if main:
            L += ["", "### Recovery of true effects, main scenario (mean [90% interval])", ""] + recovery_table(main)
            if first is None:
                first = main
                L += ["", "### TV distortion by rollup, main scenario", "",
                      "| Version | Mean abs error (% of avg month) | Max abs error | Corr. with truth | Total vs truth |",
                      "|---|---|---|---|---|"]
                L += [f"| {x['version']} | {x['mean_abs_err_pct_of_avg_month']:.1f}% | {x['max_abs_err_pct_of_avg_month']:.1f}% | "
                      f"{x['corr_with_oracle']:.2f} | {x['total_vs_oracle_pct']:+.2f}% |" for x in main["distortion"]]
        L.append("")
    ev = ROOT / "reports/validation/spec_reader_eval.json"
    if ev.exists():
        s = json.loads(ev.read_text())["summary"]
        L += ["## Spec reader evaluation (recorded Claude readings; not independent, see L-04)", "",
              "| Field | Raw accuracy | After verification |", "|---|---|---|"]
        L += [f"| {f} | {s[f]['raw_accuracy']:.0%} | {s[f]['verified_accuracy']:.0%} |"
              for f in ("grain", "calendar_system", "week_start_day", "date_label")]
        L += ["", f"Misaligned specs that passed the gate: **{s['unsafe_passes']} of {s['n_specs']}**.", ""]
    out = "\n".join(L)
    (ROOT / "docs" / "results_log.md").write_text(out)
    return out


if __name__ == "__main__":
    print(build())
